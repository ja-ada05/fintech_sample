-- =====================================================================
-- Fintech bank database for PostgreSQL 14+
--
-- Tables 1-17 are ported from the SQL Server project
--   github.com/Xue-Liu-Alexia/Bank-Database-Design_SQL
-- (names converted to snake_case, a few design problems fixed; see
-- the "CHANGES" notes next to each table).
-- Tables 18-25 are NEW, added for the dashboard project.
--
-- Run:  psql -v ON_ERROR_STOP=1 -d <your_db> -f bank_schema_postgres.sql
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- for password/answer hashing in seed data

DROP SCHEMA IF EXISTS bank CASCADE;
CREATE SCHEMA bank;
SET search_path = bank, public;

-- ---------------------------------------------------------------------
-- 1-3. Account reference tables (ported)
-- ---------------------------------------------------------------------
CREATE TABLE account_type (
    account_type_id  smallint     PRIMARY KEY,
    description      varchar(30)  NOT NULL UNIQUE
);

CREATE TABLE account_status_type (
    account_status_type_id  smallint     PRIMARY KEY,
    description             varchar(30)  NOT NULL UNIQUE
);

-- CHANGES: original numeric(9,9) and RAND() seed values -> numeric(7,6), fixed values
CREATE TABLE savings_interest_rate (
    interest_savings_rate_id  smallint      PRIMARY KEY,
    interest_rate_value       numeric(7,6)  NOT NULL CHECK (interest_rate_value >= 0 AND interest_rate_value < 1),
    description               varchar(40)   NOT NULL
);

-- ---------------------------------------------------------------------
-- 4. Branch (NEW)
-- ---------------------------------------------------------------------
CREATE TABLE branch (
    branch_id    integer      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    branch_name  varchar(60)  NOT NULL UNIQUE,
    city         varchar(40)  NOT NULL,
    state        varchar(30),
    opened_on    date         NOT NULL
);

-- ---------------------------------------------------------------------
-- 5. Employee (ported)
-- CHANGES: + branch_id; middle initial optional; is_manager boolean
-- ---------------------------------------------------------------------
CREATE TABLE employee (
    employee_id     integer      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    branch_id       integer      REFERENCES branch (branch_id),
    first_name      varchar(25)  NOT NULL,
    middle_initial  char(1),
    last_name       varchar(25)  NOT NULL,
    is_manager      boolean      NOT NULL DEFAULT false
);

-- ---------------------------------------------------------------------
-- 6. User logins (ported)
-- CHANGES: plain-text password -> password_hash; + role (for admin vs
-- non-admin views in the website), is_active, created_at
-- ---------------------------------------------------------------------
CREATE TABLE user_login (
    user_login_id  integer      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_name      varchar(30)  NOT NULL UNIQUE,
    password_hash  text         NOT NULL,
    role           varchar(10)  NOT NULL DEFAULT 'customer'
                                CHECK (role IN ('customer', 'agent', 'admin')),
    is_active      boolean      NOT NULL DEFAULT true,
    created_at     timestamptz  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 7. Account (ported)
-- CHANGES: money as numeric(14,2); + branch_id, opened_on (this was
-- repeated on every transaction row in the original); savings rate optional
-- ---------------------------------------------------------------------
CREATE TABLE account (
    account_id                bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    current_balance           numeric(14,2)  NOT NULL DEFAULT 0,
    account_type_id           smallint       NOT NULL REFERENCES account_type (account_type_id),
    account_status_type_id    smallint       NOT NULL REFERENCES account_status_type (account_status_type_id),
    interest_savings_rate_id  smallint       REFERENCES savings_interest_rate (interest_savings_rate_id),
    branch_id                 integer        REFERENCES branch (branch_id),
    opened_on                 date           NOT NULL
);

-- ---------------------------------------------------------------------
-- 8. Customer (ported)
-- CHANGES: removed account_id (customer_account already models the
-- many-to-many link); full SSN removed -> tax_id_last4; email unique;
-- address/phone widened; one login per customer
-- ---------------------------------------------------------------------
CREATE TABLE customer (
    customer_id     integer       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    first_name      varchar(30)   NOT NULL,
    middle_initial  char(1),
    last_name       varchar(30)   NOT NULL,
    address_line1   varchar(60)   NOT NULL,
    address_line2   varchar(60),
    city            varchar(40)   NOT NULL,
    state           varchar(30),
    postal_code     varchar(10),
    email           varchar(120)  NOT NULL UNIQUE,
    home_phone      varchar(20),
    cell_phone      varchar(20),
    work_phone      varchar(20),
    tax_id_last4    char(4),
    user_login_id   integer       UNIQUE REFERENCES user_login (user_login_id),
    created_at      timestamptz   NOT NULL DEFAULT now()
);

-- 9. Customer <-> Account (ported; added composite PK and is_primary)
CREATE TABLE customer_account (
    account_id   bigint   NOT NULL REFERENCES account (account_id),
    customer_id  integer  NOT NULL REFERENCES customer (customer_id),
    is_primary   boolean  NOT NULL DEFAULT true,
    PRIMARY KEY (account_id, customer_id)
);

-- 10. Login <-> Account (ported; added composite PK, which the original lacked)
CREATE TABLE login_account (
    user_login_id  integer  NOT NULL REFERENCES user_login (user_login_id),
    account_id     bigint   NOT NULL REFERENCES account (account_id),
    PRIMARY KEY (user_login_id, account_id)
);

-- ---------------------------------------------------------------------
-- 11-12. Security questions (ported)
-- CHANGES: original had 3 question columns + 3 answer columns in one row.
-- Now one row per question and one row per (login, question), answers hashed.
-- ---------------------------------------------------------------------
CREATE TABLE security_question (
    security_question_id  smallint      PRIMARY KEY,
    question_text         varchar(100)  NOT NULL UNIQUE
);

CREATE TABLE user_security_answer (
    user_login_id         integer   NOT NULL REFERENCES user_login (user_login_id),
    security_question_id  smallint  NOT NULL REFERENCES security_question (security_question_id),
    answer_hash           text      NOT NULL,
    PRIMARY KEY (user_login_id, security_question_id)
);

-- ---------------------------------------------------------------------
-- 13. Merchant (NEW)
-- ---------------------------------------------------------------------
CREATE TABLE merchant (
    merchant_id    integer      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    merchant_name  varchar(80)  NOT NULL,
    category       varchar(30)  NOT NULL,
    city           varchar(40)
);

-- ---------------------------------------------------------------------
-- 14. Card (NEW) - only the last 4 digits are stored, never a full card number
-- ---------------------------------------------------------------------
CREATE TABLE card (
    card_id       integer        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id    bigint         NOT NULL REFERENCES account (account_id),
    customer_id   integer        NOT NULL REFERENCES customer (customer_id),
    card_type     varchar(6)     NOT NULL CHECK (card_type IN ('debit', 'credit')),
    card_last4    char(4)        NOT NULL,
    expiry_date   date           NOT NULL,
    status        varchar(10)    NOT NULL DEFAULT 'active'
                                 CHECK (status IN ('active', 'blocked', 'expired')),
    credit_limit  numeric(14,2),
    CHECK (card_type = 'credit' OR credit_limit IS NULL)
);

-- ---------------------------------------------------------------------
-- 15. Transaction type (ported)
-- CHANGES: dropped the dangling account_reactivation_log_id column
-- ---------------------------------------------------------------------
CREATE TABLE transaction_type (
    transaction_type_id  smallint       PRIMARY KEY,
    name                 varchar(20)    NOT NULL UNIQUE,
    description          varchar(100),
    fee_amount           numeric(8,2)   NOT NULL DEFAULT 0 CHECK (fee_amount >= 0)
);

-- ---------------------------------------------------------------------
-- 16. Transaction log (ported)
-- CHANGES: removed date_opened / opening_balance / reactivation_date (those
-- are account facts, not per-transaction facts); old/new balance renamed
-- balance_before/after + generated net_change; + channel, merchant_id,
-- card_id; employee and login optional (online/ATM activity has no employee)
-- ---------------------------------------------------------------------
CREATE TABLE transaction_log (
    transaction_id       bigint         GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    transaction_date     timestamptz    NOT NULL,
    transaction_type_id  smallint       NOT NULL REFERENCES transaction_type (transaction_type_id),
    amount               numeric(14,2)  NOT NULL CHECK (amount > 0),
    account_id           bigint         NOT NULL REFERENCES account (account_id),
    customer_id          integer        NOT NULL REFERENCES customer (customer_id),
    employee_id          integer        REFERENCES employee (employee_id),
    user_login_id        integer        REFERENCES user_login (user_login_id),
    merchant_id          integer        REFERENCES merchant (merchant_id),
    card_id              integer        REFERENCES card (card_id),
    channel              varchar(10)    NOT NULL DEFAULT 'branch'
                                        CHECK (channel IN ('branch', 'atm', 'online', 'mobile', 'pos')),
    balance_before       numeric(14,2)  NOT NULL,
    balance_after        numeric(14,2)  NOT NULL,
    net_change           numeric(14,2)  GENERATED ALWAYS AS (balance_after - balance_before) STORED
);

-- ---------------------------------------------------------------------
-- 17-18. Failed transactions (ported)
-- CHANGES: XML file-path column -> details jsonb; + account_id; identity PKs
-- ---------------------------------------------------------------------
CREATE TABLE failed_transaction_error_type (
    failed_transaction_error_type_id  smallint     PRIMARY KEY,
    description                       varchar(80)  NOT NULL UNIQUE
);

CREATE TABLE failed_transaction_log (
    failed_transaction_id             bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    failed_transaction_error_type_id  smallint     NOT NULL REFERENCES failed_transaction_error_type (failed_transaction_error_type_id),
    account_id                        bigint       REFERENCES account (account_id),
    error_time                        timestamptz  NOT NULL,
    details                           jsonb
);

-- ---------------------------------------------------------------------
-- 19. Overdraft log (ported)
-- CHANGES: original used account_id as the PK (one overdraft per account
-- ever); now an identity PK + FK; XML column -> jsonb
-- ---------------------------------------------------------------------
CREATE TABLE overdraft_log (
    overdraft_id      bigint         GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id        bigint         NOT NULL REFERENCES account (account_id),
    overdraft_date    timestamptz    NOT NULL,
    overdraft_amount  numeric(14,2)  NOT NULL CHECK (overdraft_amount > 0),
    details           jsonb
);

-- ---------------------------------------------------------------------
-- 20. Login error log (ported)
-- CHANGES: identity PK, optional FK to the login that failed, details jsonb
-- ---------------------------------------------------------------------
CREATE TABLE login_error_log (
    error_log_id   bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_login_id  integer      REFERENCES user_login (user_login_id),
    error_time     timestamptz  NOT NULL,
    details        jsonb
);

-- ---------------------------------------------------------------------
-- 21-22. Loans (NEW)
-- ---------------------------------------------------------------------
CREATE TABLE loan (
    loan_id                  bigint         GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id              integer        NOT NULL REFERENCES customer (customer_id),
    disbursement_account_id  bigint         REFERENCES account (account_id),
    approved_by_employee_id  integer        REFERENCES employee (employee_id),
    loan_type                varchar(10)    NOT NULL CHECK (loan_type IN ('personal', 'auto', 'home', 'business')),
    principal                numeric(14,2)  NOT NULL CHECK (principal > 0),
    annual_rate              numeric(7,6)   NOT NULL CHECK (annual_rate >= 0 AND annual_rate < 1),
    term_months              smallint       NOT NULL CHECK (term_months > 0),
    originated_on            date           NOT NULL,
    status                   varchar(10)    NOT NULL DEFAULT 'active'
                                            CHECK (status IN ('active', 'paid_off', 'delinquent', 'defaulted'))
);

CREATE TABLE loan_payment (
    loan_payment_id  bigint         GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    loan_id          bigint         NOT NULL REFERENCES loan (loan_id) ON DELETE CASCADE,
    installment_no   smallint       NOT NULL CHECK (installment_no > 0),
    due_date         date           NOT NULL,
    amount_due       numeric(14,2)  NOT NULL CHECK (amount_due > 0),
    paid_on          date,
    amount_paid      numeric(14,2)  NOT NULL DEFAULT 0 CHECK (amount_paid >= 0),
    UNIQUE (loan_id, installment_no),
    CHECK (paid_on IS NOT NULL OR amount_paid = 0)
);

-- ---------------------------------------------------------------------
-- 23. Fraud alert (NEW) - flags on individual transactions (ML output goes here)
-- ---------------------------------------------------------------------
CREATE TABLE fraud_alert (
    alert_id               bigint        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    transaction_id         bigint        NOT NULL REFERENCES transaction_log (transaction_id),
    rule_triggered         varchar(40)   NOT NULL,
    risk_score             numeric(4,3)  NOT NULL CHECK (risk_score BETWEEN 0 AND 1),
    status                 varchar(10)   NOT NULL DEFAULT 'open'
                                         CHECK (status IN ('open', 'reviewing', 'confirmed', 'dismissed')),
    created_at             timestamptz   NOT NULL DEFAULT now(),
    reviewed_by_employee_id integer      REFERENCES employee (employee_id)
);

-- ---------------------------------------------------------------------
-- 24. KYC document (NEW) - stores a reference to the document, not its number
-- ---------------------------------------------------------------------
CREATE TABLE kyc_document (
    kyc_document_id          bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id              integer      NOT NULL REFERENCES customer (customer_id),
    document_type            varchar(20)  NOT NULL
                                          CHECK (document_type IN ('passport', 'drivers_license', 'national_id', 'utility_bill')),
    document_ref             varchar(40)  NOT NULL,
    status                   varchar(10)  NOT NULL DEFAULT 'pending'
                                          CHECK (status IN ('pending', 'verified', 'rejected')),
    submitted_at             timestamptz  NOT NULL DEFAULT now(),
    verified_by_employee_id  integer      REFERENCES employee (employee_id),
    verified_at              timestamptz
);

-- ---------------------------------------------------------------------
-- 25. Audit log (NEW) - who did what in the app (useful for the admin view)
-- ---------------------------------------------------------------------
CREATE TABLE audit_log (
    audit_id        bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    actor_login_id  integer      REFERENCES user_login (user_login_id),
    action          varchar(40)  NOT NULL,
    entity_type     varchar(30)  NOT NULL,
    entity_id       varchar(40),
    occurred_at     timestamptz  NOT NULL DEFAULT now(),
    details         jsonb
);

-- =====================================================================
-- Indexes (foreign keys and common dashboard filters)
-- =====================================================================
CREATE INDEX ix_account_branch        ON account (branch_id);
CREATE INDEX ix_account_status        ON account (account_status_type_id);
CREATE INDEX ix_customer_last_name    ON customer (last_name);
CREATE INDEX ix_txn_account_date      ON transaction_log (account_id, transaction_date DESC);
CREATE INDEX ix_txn_date              ON transaction_log (transaction_date);
CREATE INDEX ix_txn_customer          ON transaction_log (customer_id);
CREATE INDEX ix_failed_txn_time       ON failed_transaction_log (error_time);
CREATE INDEX ix_loan_customer         ON loan (customer_id);
CREATE INDEX ix_loan_status           ON loan (status);
CREATE INDEX ix_loan_payment_unpaid   ON loan_payment (due_date) WHERE amount_paid = 0;
CREATE INDEX ix_fraud_alert_status    ON fraud_alert (status);
CREATE INDEX ix_audit_time            ON audit_log (occurred_at);
CREATE INDEX ix_audit_actor           ON audit_log (actor_login_id);

