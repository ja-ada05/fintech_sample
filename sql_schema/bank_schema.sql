-- One row per account with type, status, branch and holder names
CREATE VIEW v_account_overview AS
SELECT a.account_id,
       aty.description  AS account_type,
       ast.description  AS status,
       a.current_balance,
       r.interest_rate_value,
       b.branch_name,
       a.opened_on,
       string_agg(c.first_name || ' ' || c.last_name, ', ' ORDER BY c.customer_id) AS holders
FROM account a
JOIN account_type aty        ON aty.account_type_id = a.account_type_id
JOIN account_status_type ast ON ast.account_status_type_id = a.account_status_type_id
LEFT JOIN savings_interest_rate r ON r.interest_savings_rate_id = a.interest_savings_rate_id
LEFT JOIN branch b           ON b.branch_id = a.branch_id
LEFT JOIN customer_account ca ON ca.account_id = a.account_id
LEFT JOIN customer c         ON c.customer_id = ca.customer_id
GROUP BY a.account_id, aty.description, ast.description, a.current_balance,
         r.interest_rate_value, b.branch_name, a.opened_on;

-- Loan book by type and status
CREATE VIEW v_loan_portfolio AS
SELECT loan_type,
       status,
       count(*)                          AS loans,
       sum(principal)                    AS total_principal,
       round(avg(annual_rate) * 100, 2)  AS avg_rate_pct
FROM loan
GROUP BY loan_type, status;

-- Installments past due and not fully paid
CREATE VIEW v_overdue_installments AS
SELECT l.loan_id,
       c.customer_id,
       c.first_name || ' ' || c.last_name AS customer_name,
       lp.installment_no,
       lp.due_date,
       lp.amount_due - lp.amount_paid     AS amount_outstanding,
       CURRENT_DATE - lp.due_date         AS days_overdue
FROM loan_payment lp
JOIN loan l     ON l.loan_id = lp.loan_id
JOIN customer c ON c.customer_id = l.customer_id
WHERE lp.due_date < CURRENT_DATE
  AND lp.amount_paid < lp.amount_due;

-- Monthly transaction volume by type (refresh with:
--   REFRESH MATERIALIZED VIEW CONCURRENTLY mv_monthly_transaction_summary;)
CREATE MATERIALIZED VIEW mv_monthly_transaction_summary AS
SELECT date_trunc('month', t.transaction_date)::date AS month,
       tt.name                                      AS transaction_type,
       count(*)                                     AS txn_count,
       sum(t.amount)                                AS total_amount,
       sum(tt.fee_amount)                           AS total_fees
FROM transaction_log t
JOIN transaction_type tt ON tt.transaction_type_id = t.transaction_type_id
GROUP BY 1, 2;

CREATE UNIQUE INDEX ux_mv_monthly_txn ON mv_monthly_transaction_summary (month, transaction_type);